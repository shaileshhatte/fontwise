/*
  vendor-assets.mjs — copies third-party assets into extension/ and generates
  extension/shared/bundled-fonts.js. Run with `npm run vendor` after updating
  the font or Readability packages; commit the result.
*/

import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const modules = join(root, 'node_modules');
const extension = join(root, 'extension');

const FONTS = [
  {
    slug: 'atkinson-hyperlegible',
    family: 'Fontwise Atkinson Hyperlegible',
    pkg: '@fontsource/atkinson-hyperlegible',
    css: ['400.css', '400-italic.css', '700.css', '700-italic.css'],
  },
  { slug: 'lexend', family: 'Fontwise Lexend', pkg: '@fontsource-variable/lexend', css: ['wght.css'] },
  { slug: 'literata', family: 'Fontwise Literata', pkg: '@fontsource-variable/literata', css: ['wght.css', 'wght-italic.css'] },
  {
    slug: 'opendyslexic',
    family: 'Fontwise OpenDyslexic',
    pkg: '@fontsource/opendyslexic',
    css: ['400.css', '400-italic.css', '700.css', '700-italic.css'],
  },
];

// Latin and Latin Extended cover Western, Central and Eastern European languages.
const SUBSET = /-latin(-ext)?-/;

const prop = (block, name) => block.match(new RegExp(`${name}:\\s*([^;]+);`))?.[1].trim() ?? null;

rmSync(join(extension, 'fonts'), { recursive: true, force: true });

const bundled = FONTS.map((font) => {
  const dir = join(extension, 'fonts', font.slug);
  mkdirSync(dir, { recursive: true });
  copyFileSync(join(modules, font.pkg, 'LICENSE'), join(dir, 'OFL.txt'));

  const faces = [];
  for (const cssFile of font.css) {
    const css = readFileSync(join(modules, font.pkg, cssFile), 'utf8');
    for (const [block] of css.matchAll(/@font-face\s*{[^}]*}/g)) {
      const file = block.match(/url\(\.\/files\/([^)]+\.woff2)\)/)?.[1];
      if (!file || !SUBSET.test(file)) continue;
      copyFileSync(join(modules, font.pkg, 'files', file), join(dir, file));
      faces.push({
        file: `fonts/${font.slug}/${file}`,
        weight: prop(block, 'font-weight'),
        style: prop(block, 'font-style'),
        unicodeRange: prop(block, 'unicode-range'),
      });
    }
  }
  if (faces.length === 0) throw new Error(`No faces found for ${font.pkg}`);
  return { family: font.family, faces };
});

writeFileSync(
  join(extension, 'shared', 'bundled-fonts.js'),
  `/*
  bundled-fonts.js — GENERATED by tools/vendor-assets.mjs. Do not edit by hand.
  Open-licensed (SIL OFL 1.1) reading fonts shipped inside the extension under
  "Fontwise …" family names, so they never collide with installed fonts.
*/

'use strict';

(() => {
  const FW = (globalThis.Fontwise ??= {});
  FW.BUNDLED_FONTS = Object.freeze(${JSON.stringify(bundled, null, 2).replace(/\n/g, '\n  ')});
})();
`,
);

const readability = join(extension, 'vendor', 'readability');
rmSync(readability, { recursive: true, force: true });
mkdirSync(readability, { recursive: true });
copyFileSync(join(modules, '@mozilla/readability/Readability.js'), join(readability, 'Readability.js'));
copyFileSync(join(modules, '@mozilla/readability/LICENSE.md'), join(readability, 'LICENSE.md'));

const faceCount = bundled.reduce((n, font) => n + font.faces.length, 0);
console.log(`Vendored ${bundled.length} font families (${faceCount} faces) and Readability.`);
